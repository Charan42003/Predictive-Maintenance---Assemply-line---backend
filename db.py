async def get_latest_logs(limit: int = 15):
    # Fetch latest logs sorted by timestamp
    return await logs_collection.find().sort("timestamp", -1).limit(limit).to_list(limit)

async def get_all_tickets():
    # Fetch all tickets and apply the helper to each one
    tickets = await tickets_collection.find().to_list(None)
    
    # Apply the helper to convert ObjectId to string
    return [ticket_helper(ticket) for ticket in tickets]

