# --- HELPER FUNCTION FOR MONGODB SERIALIZATION ---
def ticket_helper(ticket) -> dict:
    """Converts MongoDB document (including ObjectId) to a serializable dictionary for FastAPI/JSON."""
    if not ticket:
        return {}
        
    # Convert the document to a mutable dictionary
    result = dict(ticket)
    
    # 1. Convert ObjectId to string (Fixes the TypeError)
    if "_id" in result:
        result["_id"] = str(result["_id"])
    
    # 2. Add a formatted time string for frontend display
    if "time_created" in result and isinstance(result["time_created"], (int, float)):
        result["time_created_str"] = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(result["time_created"]))
    
    # Ensure llm_suggestion is a list if it was stored as a list
    if isinstance(result.get("llm_suggestion"), list):
        # We don't need to do anything, it's already JSON-serializable
        pass
    else:
        # If it was incorrectly stored or is missing, ensure it's a list
        result["llm_suggestion"] = ["No specific fix plan provided by LLM."]
        
    return result
